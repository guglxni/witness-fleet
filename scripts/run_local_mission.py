"""Launch the opt-in mission on a fresh bounded loopback DB; retain all run data."""
import argparse
import json
import signal
import subprocess
import time
import uuid
from pathlib import Path

IMAGE = 'falkordb/falkordb@sha256:107455e862a824e45e8e9f5a7fbfdf5e00a08b14e13eae2577c72fd9e3f59ba6'
REPO = Path(__file__).resolve().parents[1]


def graph_command(name):
    return ['docker', 'run', '-d', '--name', name,
            '--label', 'witness-fleet.owner=local-launcher',
            '--memory', '512m', '--cpus', '1', '--restart', 'no',
            '-p', '127.0.0.1::6379', '-e', 'BROWSER=0',
            '-e', 'REDIS_ARGS=--appendonly yes --appendfsync always',
            '-v', name + ':/var/lib/falkordb/data', IMAGE]


def prepare_root(root):
    root = Path(root).expanduser()
    if root.is_symlink():
        raise ValueError('run directory cannot be a symlink')
    if root.exists() and (not root.is_dir() or any(root.iterdir())):
        raise ValueError('use a new empty run directory; retained runs are never overwritten')
    root.mkdir(parents=True, exist_ok=True)
    return root.resolve()


def parser():
    result = argparse.ArgumentParser(description=__doc__)
    result.add_argument('--run-dir', type=Path, required=True)
    result.add_argument('--port', type=int, default=8095)
    return result


def main(argv=None):
    args = parser().parse_args(argv)
    if not 1024 <= args.port <= 65535:
        raise ValueError('port must be between 1024 and 65535')
    ui = REPO / 'web/dist'
    cli = REPO / '.venv/bin/witness-fleet'
    if not (ui / 'index.html').is_file() or not cli.is_file():
        raise RuntimeError('Run uv sync --frozen --extra dev --extra simulator; then npm ci && npm run build in web/')
    root = prepare_root(args.run_dir)
    name = 'wf-local-mission-' + uuid.uuid4().hex[:12]
    receipt = {'container': name, 'volume': name, 'ui_url': f'http://127.0.0.1:{args.port}',
               'retained': True, 'run_dir': str(root), 'motion_on_startup': False}
    (root / 'launcher.json').write_text(json.dumps(receipt, indent=2) + '\n')
    child = None
    started = False

    def stop_signal(_number, _frame):
        raise KeyboardInterrupt

    original = signal.signal(signal.SIGTERM, stop_signal)
    try:
        subprocess.run(graph_command(name), check=True, capture_output=True, text=True, timeout=60)
        started = True
        details = json.loads(subprocess.check_output(['docker', 'inspect', name], text=True, timeout=15))[0]
        graph_port = int(details['NetworkSettings']['Ports']['6379/tcp'][0]['HostPort'])
        receipt['graph_port'] = graph_port
        (root / 'launcher.json').write_text(json.dumps(receipt, indent=2) + '\n')
        from falkordb import FalkorDB
        deadline = time.monotonic() + 20
        while True:
            client = None
            try:
                client = FalkorDB(host='127.0.0.1', port=graph_port, username='default')
                client.connection.ping()
                break
            except Exception:
                if time.monotonic() >= deadline:
                    raise
                time.sleep(.1)
            finally:
                if client is not None:
                    client.close()
        print(json.dumps(receipt, indent=2), flush=True)
        print('Startup is inert. Use the UI to start and explicitly release the configured demo owner.', flush=True)
        child = subprocess.Popen([str(cli), 'mission', '--run-dir', str(root / 'mission'),
                                  '--graph-port', str(graph_port), '--graph-user', 'default',
                                  '--port', str(args.port), '--ui-dir', str(ui)], cwd=REPO)
        return child.wait()
    except KeyboardInterrupt:
        return 0
    finally:
        signal.signal(signal.SIGTERM, original)
        if child is not None and child.poll() is None:
            child.terminate()
            try:
                child.wait(timeout=30)
            except subprocess.TimeoutExpired:
                child.kill()
                child.wait(timeout=10)
        if started:
            # This exact name was generated by this process. Never inspect/stop peers.
            subprocess.run(['docker', 'stop', '--timeout', '20', name], check=True, timeout=30)
            print(f'Retained run, container and volume: {root} / {name}', flush=True)


if __name__ == '__main__':
    raise SystemExit(main())
